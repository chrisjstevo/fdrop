-- The audit log in the DB: append-only, and hash-chained per node (hash = SHA-256 of the previous hash and the row),
-- so a row edited, deleted or reordered later breaks the chain from there on. Pruning moves a node's chain start to
-- audit_anchor. Operators may revoke UPDATE and DELETE on audit_event from fdrop's DB user and leave pruning to a
-- maintenance role, e.g. on PostgreSQL:
--   REVOKE UPDATE, DELETE ON audit_event FROM fdrop;  GRANT DELETE ON audit_event TO fdrop_maintenance;

CREATE TABLE audit_event (
    seq         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id          VARCHAR(40)   NOT NULL,
    ts          BIGINT        NOT NULL,
    node        VARCHAR(200)  NOT NULL,
    node_seq    BIGINT        NOT NULL,
    prev_hash   VARCHAR(64)   NOT NULL,
    hash        VARCHAR(64)   NOT NULL,
    event       VARCHAR(100)  NOT NULL,
    event_group VARCHAR(40)   NOT NULL,
    user_name   VARCHAR(255),
    ip          VARCHAR(64),
    protocol    VARCHAR(16),
    outcome     VARCHAR(16)   NOT NULL,
    summary     VARCHAR(1000) NOT NULL,
    data        TEXT          NOT NULL,
    CONSTRAINT audit_event_id UNIQUE (id),
    CONSTRAINT audit_event_chain UNIQUE (node, node_seq)
);
CREATE INDEX audit_event_ts ON audit_event (ts);
CREATE INDEX audit_event_user ON audit_event (user_name, ts);
CREATE INDEX audit_event_event ON audit_event (event, ts);

CREATE TABLE audit_anchor (
    node      VARCHAR(200) PRIMARY KEY,
    node_seq  BIGINT       NOT NULL,
    hash      VARCHAR(64)  NOT NULL,
    pruned_at BIGINT       NOT NULL
);
