-- Search: a change feed every node's index applies in order, and one text extraction per file version, shared by
-- all nodes (the text itself is stored, encrypted, under system/search-text/ in storage).

CREATE TABLE search_change (
    seq         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    op          VARCHAR(8)    NOT NULL,
    storage_key VARCHAR(1100) NOT NULL,
    to_key      VARCHAR(1100),
    at          BIGINT        NOT NULL
);
CREATE INDEX search_change_at ON search_change (at);

CREATE TABLE search_extract (
    storage_key   VARCHAR(1100) NOT NULL,
    version       VARCHAR(200)  NOT NULL,
    state         VARCHAR(16)   NOT NULL,
    text_key      VARCHAR(200),
    type          VARCHAR(16),
    claimed_by    VARCHAR(64),
    claimed_until BIGINT,
    attempts      INT           NOT NULL DEFAULT 0,
    updated_at    BIGINT        NOT NULL,
    PRIMARY KEY (storage_key, version)
);
